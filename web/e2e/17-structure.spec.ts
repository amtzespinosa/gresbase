import { expect, test } from '@playwright/test'
import { scalar, sql } from './helpers'

const columns = (request: Parameters<typeof scalar>[0]) =>
  scalar(
    request,
    `SELECT string_agg(column_name || ' ' || data_type, ', ' ORDER BY ordinal_position)
     FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'e2e_notes'`,
  )

test('create a table, add a column, rename it and delete it, seeing the SQL each time', async ({
  page,
  request,
}) => {
  await sql(request, 'DROP TABLE IF EXISTS public.e2e_notes')
  await page.goto('/tables/public/users')

  await page.getByRole('button', { name: 'New table' }).click()
  let dialog = page.getByRole('dialog', { name: 'New table' })
  await dialog.getByLabel('Table name').fill('e2e_notes')
  await expect(dialog.locator('pre')).toContainText('CREATE TABLE "public"."e2e_notes"')
  await expect(dialog.locator('pre')).toContainText('"id" bigint GENERATED BY DEFAULT AS IDENTITY')
  await dialog.getByRole('button', { name: 'Create table' }).click()
  await expect(page).toHaveURL(/\/tables\/public\/e2e_notes\?tab=structure$/)
  expect(await columns(request)).toBe('id bigint')

  await page.getByRole('button', { name: 'Add column' }).click()
  dialog = page.getByRole('dialog', { name: 'Add a column to public.e2e_notes' })
  await dialog.getByLabel('Column name').fill('body')
  await dialog.getByLabel('Type', { exact: true }).fill('text')
  await expect(dialog.locator('pre')).toHaveText(
    'ALTER TABLE "public"."e2e_notes" ADD COLUMN "body" text;',
  )
  await expect(dialog).toContainText('Locks the table (ACCESS EXCLUSIVE)')
  await dialog.getByRole('button', { name: 'Add column' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('region', { name: 'Columns' })).toContainText('body')
  expect(await columns(request)).toBe('id bigint, body text')

  await page.getByRole('button', { name: 'Change column body' }).click()
  await page.getByRole('menuitem', { name: 'Rename…' }).click()
  dialog = page.getByRole('dialog', { name: 'Rename column body' })
  await dialog.getByLabel('New name').fill('content')
  await expect(dialog.locator('pre')).toHaveText(
    'ALTER TABLE "public"."e2e_notes" RENAME COLUMN "body" TO "content";',
  )
  await dialog.getByRole('button', { name: 'Rename' }).click()
  await expect(dialog).toBeHidden()
  expect(await columns(request)).toBe('id bigint, content text')

  await page.getByRole('button', { name: 'Change column content' }).click()
  await page.getByRole('menuitem', { name: 'Delete column…' }).click()
  dialog = page.getByRole('dialog', { name: 'Delete column content' })
  const confirm = dialog.getByRole('button', { name: 'Delete column' })
  await expect(dialog.locator('pre')).toHaveText(
    'ALTER TABLE "public"."e2e_notes" DROP COLUMN "content";',
  )
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel('Type content to confirm').fill('content')
  await confirm.click()
  await expect(dialog).toBeHidden()
  expect(await columns(request)).toBe('id bigint')

  await sql(request, 'DROP TABLE public.e2e_notes')
})
