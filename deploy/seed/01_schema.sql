-- Demo schema for development and integration tests.
-- Covers every case the MVP needs: varied types, identity, enum, arrays, bytea, cascades, SET NULL,
-- a table without primary key, odd identifiers, a view, a materialized view, a partitioned table,
-- a user trigger and an extra schema. Compatible with PostgreSQL 12–19.

-- gen_random_uuid() is core since 13; on 12 it comes from pgcrypto (in the official image's contrib).
DO $$
BEGIN
  IF current_setting('server_version_num')::int < 130000 THEN
    CREATE EXTENSION IF NOT EXISTS pgcrypto;
  END IF;
END
$$;

CREATE TYPE plan_t AS ENUM ('free', 'pro', 'team');

CREATE TABLE orgs (
  id         int8 GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       text NOT NULL UNIQUE,
  plan       plan_t NOT NULL DEFAULT 'free',
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE orgs IS 'Customer organizations';

CREATE TABLE users (
  id         int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id     int8 REFERENCES orgs (id),
  uuid       uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  email      text NOT NULL UNIQUE,
  full_name  text,
  is_active  boolean NOT NULL DEFAULT true,
  plan       plan_t NOT NULL DEFAULT 'free',
  balance    numeric(12, 2) NOT NULL DEFAULT 0,
  birth_date date,
  tags       text[] NOT NULL DEFAULT '{}',
  settings   jsonb NOT NULL DEFAULT '{}',
  last_ip    inet,
  avatar     bytea,
  bio        text,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE users IS 'Application users';
COMMENT ON COLUMN users.bio IS 'Free text; one row holds more than 20 KB';
CREATE INDEX users_org_id_idx ON users (org_id);
CREATE INDEX users_created_at_idx ON users (created_at DESC);

CREATE TABLE projects (
  id         int8 GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  org_id     int8 NOT NULL REFERENCES orgs (id) ON DELETE CASCADE,
  owner_id   int8 REFERENCES users (id),
  name       text NOT NULL,
  budget     numeric(12, 2),
  estimate   interval,
  starts_on  date,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, name)
);

CREATE FUNCTION touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END
$$;

CREATE TRIGGER projects_touch_updated_at
  BEFORE UPDATE ON projects
  FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

CREATE TABLE invoices (
  id        int8 GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  org_id    int8 NOT NULL REFERENCES orgs (id),
  number    text NOT NULL UNIQUE,
  issued_on date NOT NULL,
  total     numeric(12, 2) NOT NULL DEFAULT 0,
  paid      boolean NOT NULL DEFAULT false,
  metadata  jsonb
);

CREATE TABLE invoice_items (
  id          int8 GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  invoice_id  int8 NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
  description text NOT NULL,
  quantity    int4 NOT NULL CHECK (quantity > 0),
  unit_price  numeric(12, 2) NOT NULL,
  amount      numeric(14, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED
);
CREATE INDEX invoice_items_invoice_id_idx ON invoice_items (invoice_id);

CREATE TABLE sessions (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    int8 REFERENCES users (id) ON DELETE SET NULL,
  ip         inet,
  user_agent text,
  duration   interval,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz
);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);

-- No primary key on purpose: the grid shows it read-only.
CREATE TABLE audit_log (
  at      timestamptz NOT NULL DEFAULT now(),
  actor   text,
  action  text NOT NULL,
  payload jsonb
);

CREATE TABLE "Weird Table" (
  id                   int4 PRIMARY KEY,
  "Column With Spaces" text,
  "select"             text
);

CREATE TABLE "MixedCase" (
  "Id"          int4 PRIMARY KEY,
  "DisplayName" text NOT NULL
);

CREATE VIEW active_users AS
  SELECT id, email, full_name, plan FROM users WHERE is_active;

CREATE MATERIALIZED VIEW org_stats AS
  SELECT o.id, o.name, count(u.id) AS users
  FROM orgs o LEFT JOIN users u ON u.org_id = o.id
  GROUP BY o.id, o.name;

CREATE TABLE events (
  id          bigserial,
  occurred_at timestamptz NOT NULL,
  kind        text NOT NULL,
  payload     jsonb,
  PRIMARY KEY (id, occurred_at)
) PARTITION BY RANGE (occurred_at);
CREATE TABLE events_2025 PARTITION OF events FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE events_2026 PARTITION OF events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

CREATE SCHEMA billing;

CREATE TABLE billing.plans (
  code          plan_t PRIMARY KEY,
  monthly_price numeric(12, 2) NOT NULL,
  features      text[] NOT NULL DEFAULT '{}'
);

CREATE TABLE billing.payments (
  id         int8 GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  invoice_id int8 NOT NULL REFERENCES public.invoices (id),
  amount     numeric(12, 2) NOT NULL,
  paid_at    timestamptz NOT NULL DEFAULT now()
);
